//! Self-contained HTML / Markdown run reports rendered from a history detail.
//! Port of the Python `history/report.py`.

use serde_json::Value;

const BEACON_URL: &str = "https://beacon-tester.vercel.app";

fn esc(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;").replace('\'', "&#x27;")
}

fn text(v: &Value) -> String {
    match v {
        Value::String(s) if !s.is_empty() => s.clone(),
        Value::Null | Value::String(_) => "—".into(),
        other => other.to_string(),
    }
}

fn capitalize(s: &str) -> String {
    let mut c = s.chars();
    c.next().map_or(String::new(), |f| f.to_uppercase().chain(c.flat_map(|x| x.to_lowercase())).collect())
}

fn fmt_ms(v: &Value) -> String {
    v.as_f64().map_or("—".into(), |f| format!("{} ms", f.round() as i64))
}

fn fmt_rps(v: &Value) -> String {
    v.as_f64().map_or("—".into(), |f| format!("{f:.1}"))
}

fn fmt_duration(v: &Value) -> String {
    match v.as_f64() {
        Some(ms) if ms != 0.0 => {
            let s = ms / 1000.0;
            if s < 60.0 {
                format!("{s:.1}s")
            } else {
                format!("{}m {}s", s as i64 / 60, s as i64 % 60)
            }
        }
        _ => "—".into(),
    }
}

fn fmt_dt(v: &Value) -> String {
    match v.as_str() {
        None | Some("") => "—".into(),
        Some(s) => chrono::DateTime::parse_from_rfc3339(s)
            .map(|d| d.format("%Y-%m-%d %H:%M:%S UTC").to_string())
            .unwrap_or_else(|_| s.to_string()),
    }
}

fn int(m: &Value, k: &str) -> i64 {
    m[k].as_i64().unwrap_or(0)
}

fn success_rate(m: &Value) -> String {
    let attempts = int(m, "attempts");
    if attempts == 0 {
        return "—".into();
    }
    format!("{:.1}%", int(m, "success") as f64 / attempts as f64 * 100.0)
}

fn summary_rows(d: &Value) -> Vec<(&'static str, String)> {
    let m = &d["metrics"];
    vec![
        ("Attempts", int(m, "attempts").to_string()),
        ("Success", format!("{} ({})", int(m, "success"), success_rate(m))),
        ("Rate-limited", int(m, "rate_limited").to_string()),
        ("Errors", int(m, "errors").to_string()),
        ("Avg RPS", fmt_rps(&m["average_rps"])),
        ("Peak RPS", fmt_rps(&m["peak_rps"])),
        ("Latency p50", fmt_ms(&m["p50_ms"])),
        ("Latency p95", fmt_ms(&m["p95_ms"])),
        ("Latency p99", fmt_ms(&m["p99_ms"])),
        ("Latency max", fmt_ms(&m["max_latency_ms"])),
        ("Latency min", fmt_ms(&m["min_latency_ms"])),
    ]
}

fn meta_rows(d: &Value) -> Vec<(&'static str, String)> {
    vec![
        ("Project", text(&d["project_name"])),
        ("Target Endpoint", text(&d["target_name"])),
        ("Execution Mode", capitalize(&text(&d["mode"]))),
        ("Run Status", capitalize(&text(&d["status"]))),
        ("Started At", fmt_dt(&d["started_at"])),
        ("Completed At", fmt_dt(&d["completed_at"])),
        ("Total Duration", fmt_duration(&d["duration_ms"])),
    ]
}

fn generated_at(d: &Value) -> String {
    fmt_dt(if d["completed_at"].is_string() { &d["completed_at"] } else { &d["started_at"] })
}

fn steps(d: &Value) -> Vec<Value> {
    d["steps"].as_array().cloned().unwrap_or_default()
}

pub fn render_markdown(d: &Value) -> String {
    let mut out = vec![format!("# Beacon Run Report — {}", text(&d["target_name"])), String::new()];
    out.extend(meta_rows(d).into_iter().map(|(k, v)| format!("- **{k}:** {v}")));
    out.extend(["".into(), "## Summary".into(), "".into(), "| Metric | Value |".into(), "| --- | --- |".into()]);
    out.extend(summary_rows(d).into_iter().map(|(k, v)| format!("| {k} | {v} |")));
    out.push(String::new());
    let steps = steps(d);
    if steps.len() > 1 {
        out.extend(["## Steps".into(), "".into(), "| # | Endpoint | Method | Status |".into(), "| --- | --- | --- | --- |".into()]);
        for s in &steps {
            out.push(format!("| {} | {} | {} | {} |", s["sequence"], text(&s["endpoint_name"]), text(&s["method"]), text(&s["status"])));
        }
        out.push(String::new());
    }
    out.push("---".into());
    out.push(format!("Generated by [Beacon]({BEACON_URL}) · {}", generated_at(d)));
    out.join("\n") + "\n"
}

fn svg_chart(points: &[(f64, f64)], title: &str, color: &str, grad: &str, unit: &str) -> String {
    let pts: Vec<_> = points.iter().filter(|(x, y)| x.is_finite() && y.is_finite()).collect();
    if pts.len() < 2 {
        return format!(r#"<div class="chart-box"><div class="chart-title">{}</div><div class="chart-empty">Insufficient telemetry samples for chart rendering</div></div>"#, esc(title));
    }
    let (w, h, pl, pr, pt, pb) = (740.0, 160.0, 45.0, 15.0, 15.0, 25.0);
    let min_x = pts.iter().map(|p| p.0).fold(f64::INFINITY, f64::min);
    let mut max_x = pts.iter().map(|p| p.0).fold(f64::NEG_INFINITY, f64::max);
    if max_x == min_x {
        max_x = min_x + 1.0;
    }
    let max_y = pts.iter().map(|p| p.1).fold(0.0, f64::max);
    let max_y = if max_y == 0.0 { 1.0 } else { max_y } * 1.15;
    let mx = |x: f64| pl + (x - min_x) / (max_x - min_x) * (w - pl - pr);
    let my = |y: f64| h - pb - y / max_y * (h - pt - pb);
    let poly: Vec<String> = pts.iter().map(|(x, y)| format!("{:.1},{:.1}", mx(*x), my(*y))).collect();
    let poly = poly.join(" ");
    let area = format!("{:.1},{:.1} {poly} {:.1},{:.1}", mx(pts[0].0), h - pb, mx(pts[pts.len() - 1].0), h - pb);
    let grid: String = [0.0, 0.5, 1.0]
        .iter()
        .map(|r| {
            let yv = r * max_y;
            let cy = my(yv);
            let label = if unit == "ms" { format!("{}{unit}", yv.round() as i64) } else { format!("{yv:.1}{unit}") };
            format!(
                r##"<line x1="{pl}" y1="{cy:.1}" x2="{}" y2="{cy:.1}" stroke="#e5e7eb" stroke-dasharray="3,3" /><text x="{}" y="{:.1}" fill="#9ca3af" font-size="9" text-anchor="end">{}</text>"##,
                w - pr,
                pl - 6.0,
                cy + 4.0,
                esc(&label)
            )
        })
        .collect();
    format!(
        r#"<div class="chart-box"><div class="chart-title">{}</div><svg viewBox="0 0 {w} {h}" class="svg-chart"><defs><linearGradient id="{grad}" x1="0" y1="0" x2="0" y2="1"><stop offset="0%" stop-color="{color}" stop-opacity="0.3"/><stop offset="100%" stop-color="{color}" stop-opacity="0.0"/></linearGradient></defs>{grid}<polygon points="{area}" fill="url(#{grad})" /><polyline points="{poly}" fill="none" stroke="{color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" /></svg></div>"#,
        esc(title)
    )
}

fn rows_html(rows: Vec<(&'static str, String)>) -> String {
    rows.into_iter().map(|(k, v)| format!("<tr><th>{}</th><td>{}</td></tr>", esc(k), esc(&v))).collect()
}

fn cards(items: &[(&str, String, &str)], pct: bool) -> String {
    items
        .iter()
        .map(|(l, v, c)| {
            if pct {
                format!(r#"<div class="card pct-card"><div class="l" style="color:{c}">{}</div><div class="v-sm">{}</div></div>"#, esc(l), esc(v))
            } else {
                format!(r#"<div class="card"><div class="v" style="color:{c}">{}</div><div class="l">{}</div></div>"#, esc(v), esc(l))
            }
        })
        .collect()
}

fn outcome_bar(m: &Value) -> String {
    let attempts = int(m, "attempts");
    if attempts == 0 {
        return String::new();
    }
    let (s, r, e) = (int(m, "success"), int(m, "rate_limited"), int(m, "errors"));
    let p = |n: i64| n as f64 / attempts as f64 * 100.0;
    format!(
        r#"<h2>Outcome Breakdown</h2><div class="dist-container"><div class="dist-bar"><div class="dist-seg seg-success" style="width: {:.1}%"></div><div class="dist-seg seg-rl" style="width: {:.1}%"></div><div class="dist-seg seg-error" style="width: {:.1}%"></div></div><div class="dist-legend"><span class="leg-item"><span class="dot bg-success"></span> Success: <strong>{s}</strong> ({:.1}%)</span><span class="leg-item"><span class="dot bg-rl"></span> Rate-limited: <strong>{r}</strong> ({:.1}%)</span><span class="leg-item"><span class="dot bg-error"></span> Errors: <strong>{e}</strong> ({:.1}%)</span></div></div>"#,
        p(s), p(r), p(e), p(s), p(r), p(e)
    )
}

fn steps_html(d: &Value) -> String {
    let steps = steps(d);
    if steps.len() <= 1 {
        return String::new();
    }
    let rows: String = steps
        .iter()
        .map(|s| {
            format!(
                r#"<tr><td>{}</td><td>{}</td><td><span class="badge method">{}</span></td><td>{}</td></tr>"#,
                s["sequence"].as_i64().unwrap_or(0) + 1,
                esc(&text(&s["endpoint_name"])),
                esc(&text(&s["method"])),
                esc(&text(&s["status"]))
            )
        })
        .collect();
    format!(r#"<h2>Scenario Executed Steps</h2><table class="grid"><thead><tr><th>#</th><th>Endpoint</th><th>Method</th><th>Status</th></tr></thead><tbody>{rows}</tbody></table>"#)
}

