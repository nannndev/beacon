pub fn render_html(d: &Value) -> String {
    let m = &d["metrics"];
    let title = esc(&text(&d["target_name"]));
    let status = d["status"].as_str().unwrap_or("completed").to_string();
    let badge = if status.eq_ignore_ascii_case("completed") && int(m, "errors") == 0 { "#10b981" } else { "#ef4444" };
    let samples = d["samples"].as_array().cloned().unwrap_or_default();
    let series = |field: &str| -> Vec<(f64, f64)> {
        samples.iter().filter_map(|s| Some((s["elapsed_ms"].as_f64().unwrap_or(0.0), s[field].as_f64()?))).collect()
    };
    let stat_cards = cards(
        &[
            ("Attempts", int(m, "attempts").to_string(), "#0ea5e9"),
            ("Success Rate", success_rate(m), "#10b981"),
            ("Rate-limited", int(m, "rate_limited").to_string(), "#f59e0b"),
            ("Errors", int(m, "errors").to_string(), "#ef4444"),
            ("p95 Latency", fmt_ms(&m["p95_ms"]), "#8b5cf6"),
            ("Peak RPS", fmt_rps(&m["peak_rps"]), "#0284c7"),
        ],
        false,
    );
    let pct_cards = cards(
        &[
            ("p50", fmt_ms(&m["p50_ms"]), "#0ea5e9"),
            ("p95", fmt_ms(&m["p95_ms"]), "#8b5cf6"),
            ("p99", fmt_ms(&m["p99_ms"]), "#a855f7"),
            ("Max", fmt_ms(&m["max_latency_ms"]), "#ef4444"),
        ],
        true,
    );
    format!(
        r#"<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Beacon Executive Report — {title}</title>
  <style>{CSS}</style>
</head>
<body>
  <div class="wrap">
    <div class="banner">
      <div class="banner-top">
        <div class="brand"><span class="brand-dot"></span> BEACON EXECUTIVE REPORT</div>
        <button class="print-btn" onclick="window.print()">Print / Save PDF</button>
      </div>
      <h1>{title} <span class="status-tag" style="background:{badge}">{status}</span></h1>
      <div class="meta-subtitle">{project} · {mode} mode run</div>
    </div>
    <div class="cards">{stat_cards}</div>
    <h2>Latency Percentiles</h2>
    <div class="cards">{pct_cards}</div>
    {outcome}
    <h2>Performance Telemetry Trends</h2>
    <div class="charts-grid">{latency}{rps}</div>
    <h2>Run Overview</h2>
    <table class="meta"><tbody>{meta}</tbody></table>
    <h2>Metrics Summary</h2>
    <table class="meta"><tbody>{summary}</tbody></table>
    {steps}
    <footer>Generated by <a href="{BEACON_URL}">Beacon Performance Workspace</a> · {generated}</footer>
  </div>
</body>
</html>
"#,
        status = esc(&status),
        project = esc(d["project_name"].as_str().unwrap_or("Beacon Project")),
        mode = esc(&capitalize(d["mode"].as_str().unwrap_or("load"))),
        outcome = outcome_bar(m),
        latency = svg_chart(&series("latency_ms"), "Latency Over Time (ms)", "#0ea5e9", "grad_latency", "ms"),
        rps = svg_chart(&series("instantaneous_rps"), "Throughput Over Time (RPS)", "#10b981", "grad_rps", " rps"),
        meta = rows_html(meta_rows(d)),
        summary = rows_html(summary_rows(d)),
        steps = steps_html(d),
        generated = esc(&generated_at(d)),
    )
}
