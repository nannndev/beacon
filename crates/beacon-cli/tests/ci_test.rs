mod common;

use common::*;
use std::process::Command;

fn init_git_repo(root: &std::path::Path) {
    let status = Command::new("git")
        .args(["init", "-q"])
        .current_dir(root)
        .status()
        .expect("git init");
    assert!(status.success());
}

fn build_project(root: &std::path::Path, env_vars: &[(&str, Option<&str>)]) {
    ProjectBuilder::new(root)
        .environment("env-1", "CI", "https://example.test", env_vars)
        .endpoint("ep-1", "Ping", "/get", "GET", "")
        .build("proj-1", "Sample Project", "env-1");
}

#[test]
fn ci_init_github_dry_run_prints_yaml_without_writing() {
    let repo = tempfile::tempdir().unwrap();
    init_git_repo(repo.path());
    let project_dir = repo.path().join("api-tests");
    std::fs::create_dir_all(&project_dir).unwrap();
    build_project(&project_dir, &[("api_token", Some("placeholder"))]);

    let output = run_cli(&[
        "ci",
        "init",
        "github",
        project_dir.to_str().unwrap(),
        "--dry-run",
        "--cli-version",
        "0.4.8",
    ]);
    assert!(output.status.success(), "stderr: {}", stderr(&output));
    let yaml = stdout(&output);
    assert!(yaml.contains("name: Beacon API tests"));
    assert!(yaml.contains("download/v0.4.8"));
    assert!(yaml.contains("BEACON_PROJECT: \"api-tests\""));
    assert!(!repo.path().join(".github/workflows/beacon.yml").exists());
}

#[test]
fn ci_init_github_creates_then_is_unchanged_on_rerun() {
    let repo = tempfile::tempdir().unwrap();
    init_git_repo(repo.path());
    let project_dir = repo.path().join("api-tests");
    std::fs::create_dir_all(&project_dir).unwrap();
    build_project(&project_dir, &[]);

    let first = run_cli(&["ci", "init", "github", project_dir.to_str().unwrap()]);
    assert!(first.status.success(), "stderr: {}", stderr(&first));
    assert!(stdout(&first).contains("Created:"));

    let workflow_path = repo.path().join(".github/workflows/beacon.yml");
    assert!(workflow_path.is_file());
    let content = std::fs::read_to_string(&workflow_path).unwrap();
    assert!(content.contains("name: Beacon API tests"));
    assert!(content.starts_with("# Generated by Beacon CLI"));

    let second = run_cli(&["ci", "init", "github", project_dir.to_str().unwrap()]);
    assert!(second.status.success());
    assert!(stdout(&second).contains("Already up to date:"));
}

#[test]
fn ci_init_github_refuses_to_replace_a_different_workflow_without_force() {
    let repo = tempfile::tempdir().unwrap();
    init_git_repo(repo.path());
    let project_dir = repo.path().join("api-tests");
    std::fs::create_dir_all(&project_dir).unwrap();
    build_project(&project_dir, &[]);

    let workflow_dir = repo.path().join(".github/workflows");
    std::fs::create_dir_all(&workflow_dir).unwrap();
    std::fs::write(workflow_dir.join("beacon.yml"), "name: Not Beacon's workflow\n").unwrap();

    let output = run_cli(&["ci", "init", "github", project_dir.to_str().unwrap()]);
    assert_eq!(output.status.code(), Some(2));
    assert!(stderr(&output).contains("--force"));

    let forced = run_cli(&["ci", "init", "github", project_dir.to_str().unwrap(), "--force"]);
    assert!(forced.status.success(), "stderr: {}", stderr(&forced));
    assert!(stdout(&forced).contains("Updated:"));
}

#[test]
fn ci_init_github_maps_secret_shaped_variables_to_beacon_var_names() {
    let repo = tempfile::tempdir().unwrap();
    init_git_repo(repo.path());
    let project_dir = repo.path().join("api-tests");
    std::fs::create_dir_all(&project_dir).unwrap();
    build_project(&project_dir, &[("api_token", Some("x")), ("plain_value", Some("y"))]);

    let output = run_cli(&["ci", "init", "github", project_dir.to_str().unwrap(), "--dry-run"]);
    assert!(output.status.success());
    let yaml = stdout(&output);
    assert!(yaml.contains("BEACON_VAR_API_TOKEN: ${{ secrets.BEACON_VAR_API_TOKEN }}"));
    assert!(!yaml.contains("PLAIN_VALUE"));

    let stderr_text = stderr(&output);
    let _ = stderr_text;
}

#[test]
fn ci_init_github_outside_a_git_repo_fails_without_repo_root() {
    let dir = tempfile::tempdir().unwrap();
    build_project(dir.path(), &[]);

    let output = run_cli(&["ci", "init", "github", dir.path().to_str().unwrap()]);
    assert_eq!(output.status.code(), Some(2));
    assert!(stderr(&output).contains("Git repository"));
}
